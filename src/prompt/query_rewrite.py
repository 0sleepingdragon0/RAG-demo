"""
Query 改写 / HyDE / Step-back / Decomposition 的 Prompt 模板。
"""

QUERY_REWRITE_PROMPT = """你是一个检索查询优化专家。请将以下地质领域问题改写为 2-3 条不同表述的检索query，
每条应该覆盖原始问题的不同语义角度，便于检索到知识库中不同表述方式的文档。

原始问题：{question}

要求：
- 保持地质专业术语
- 可以添加相关同义术语（如"成矿时代"→"矿床形成时代/成矿期/同位素定年"）
- 可以用不同的粒度（全称/简称/相关矿区名）
- 以JSON输出：{{"queries": ["改写1", "改写2", "改写3"]}}"""


HYDE_PROMPT = """请针对以下地质问题，写一段假设性的专业回答（3-5句话）。
注意：不要求答案正确，只要求表述风格像地质文献/勘查报告中的专业描述。
使用地质专业术语，包含地层名称、构造描述、矿化特征、同位素数据等典型要素。

问题：{question}

假设性回答（仅用于检索，不要求事实准确）："""


STEP_BACK_PROMPT = """请将以下具体的地质问题"退一步"抽象为一个更高层的通用问题。
这个更高层问题应该涵盖回答原问题所需的背景原理知识。

原问题：{question}

规则：
- 把具体矿区/矿床名替换为该类矿床的通用概念
- 保持地质领域方向不变
- 新问题的答案应该包含回答原问题所需的理论背景

以JSON输出：{{"abstract_question": "抽象后的高层问题"}}"""


DECOMPOSE_PROMPT = """请将以下复杂地质问题拆分为最多 3 个独立的子问题。
每个子问题应该能独立检索到回答原问题所需的部分信息。

原始问题：{question}

规则：
- 子问题之间互补，合在一起覆盖原问题的所有维度
- 每个子问题关键词明确、可独立检索
- 如果原问题涉及多个对象对比，每个对象一个子问题
- 以JSON输出：{{"sub_queries": ["子问题1", "子问题2", "子问题3"]}}"""


ROUTING_PROMPT = """请判断以下地质问题应该走哪种检索策略。

问题：{question}

可选策略：
- "direct": 简单事实查询，关键词明确，单一实体
- "hyde": 含地质专业术语但问法口语化，需要弥合表达差异
- "multi": 需要从多个角度/不同表述检索
- "decompose": 包含多个子意图或对比，需要拆分处理
- "graph": 涉及实体间关联、多跳推理、"A和B有什么关系"

以JSON输出：{{"route": "策略名", "reason": "简要理由"}}"""
